/* Problem Statement:
   Write a C program to perform basic arithmetic operations using operators.
*/
#include <stdio.h>
int main() {
    int a = 10, b = 5;
    printf("Sum = %d\n", a + b);
    printf("Difference = %d\n", a - b);
    printf("Product = %d\n", a * b);
    printf("Quotient = %d\n", a / b);
    return 0;
}
